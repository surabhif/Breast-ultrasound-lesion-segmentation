describe('buildResultPdf', () => {
  it('emits a PDF with disclaimer and privacy note; omits Dice when null', async () => {
    const blob = buildResultPdf({
      previewJpeg: tinyJpeg(),
      previewWidth: 1,
      previewHeight: 1,
      clsProb: 0.42,
      dice: null,
      iou: null,
      measurements: null,
      modelVersion: '1.0.0',
      sampleLabel: 'user upload',
      generatedAt: new Date('2026-10-10T12:00:00Z'),
    })
    expect(blob.type).toBe('application/pdf')
    const buf = new Uint8Array(await blob.arrayBuffer())
    const text = new TextDecoder('latin1').decode(buf)
    expect(text.startsWith('%PDF-1.4')).toBe(true)
    expect(text).toContain('%%EOF')
    expect(text).toContain('Model version: 1.0.0')
    // Parentheses are PDF-escaped as \( \)
    expect(text).toContain('Chance cancerous: 42.0%')
    expect(text).toContain('Outline-overlap score \\(Dice\\): n/a')
    expect(text).toContain('not for clinical use')
    expect(text).toContain('Your image stays in this browser')
    expect(text).toContain('/Subtype /Image')
    expect(text).not.toMatch(/Dice: 0\./)
  })

  it('includes Dice and measurements when provided', async () => {
    const blob = buildResultPdf({
      previewJpeg: tinyJpeg(),
      previewWidth: 160,
      previewHeight: 160,
      clsProb: 0.81,
      dice: 0.77,
      iou: 0.63,
      measurements: {
        areaPx: 120,
        areaMm2: 12.5,
        longestDiameterPx: 18,
        longestDiameterMm: 4.2,
        perpendicularWidthPx: 10,
        perpendicularWidthMm: 2.1,
      },
      modelVersion: '1.0.0',
      sampleLabel: 'malignant',
    })
    const text = new TextDecoder('latin1').decode(new Uint8Array(await blob.arrayBuffer()))
    expect(text).toContain('Outline-overlap score \\(Dice\\): 0.77 out of 1')
    expect(text).toContain('IoU: 0.63')
    expect(text).toContain('Area: 120 px')
    expect(text).toContain('Longest diameter: 18.0 px')
  })
})
